// Renders ../live-probe-report.md from every ../results/*.jsonl written by live-probe.js.
// The newest row per (provider, combination, probe) wins, so a re-run of one probe updates its cell.
// Rows from a `--repeat N` run go to their own k/N stability table instead of the matrix.
'use strict';
const fs = require('fs');
const path = require('path');

const HERE = path.resolve(__dirname, '..');
const CAMPAIGN = JSON.parse(fs.readFileSync(path.join(HERE, 'campaign.json'), 'utf8'));
const MARK = {
  PASS: '✅',
  FAIL: '❌',
  PARTIAL: '🟡',
  FINDING: '🔶',
  INVALID: '⚪',
  INFO: 'ℹ️',
  ERROR: '💥',
};

function latestRows() {
  const dir = path.join(HERE, 'results');
  const rows = fs
    .readdirSync(dir)
    .filter(f => f.endsWith('.jsonl'))
    .flatMap(f =>
      fs.readFileSync(path.join(dir, f), 'utf8').trim().split('\n').filter(Boolean).map(JSON.parse),
    );
  const latest = new Map();
  for (const r of rows.sort((a, b) => a.at.localeCompare(b.at)).filter(r => !r.rep)) {
    const key = `${r.provider}|${r.combo}|${r.probe}`;
    const prev = latest.get(key);
    // a retry that passed keeps the earlier failure visible as flakiness
    latest.set(key, {
      ...r,
      flaky: prev && prev.run === r.run && r.attempt > 1 && r.verdict === 'PASS',
    });
  }
  return { all: rows, latest: [...latest.values()] };
}

const cost = r =>
  r.costUsd != null
    ? `$${r.costUsd.toFixed(3)}`
    : r.estUsd != null
      ? `~$${r.estUsd.toFixed(3)}`
      : r.premium != null
        ? `${r.premium} req`
        : '';

function matrix(provider, rows) {
  const probes = [...new Set(CAMPAIGN.combos.flatMap(c => c.probes.map(p => p.id)))].sort((a, b) =>
    a.localeCompare(b, 'en', { numeric: true }),
  );
  const mine = rows.filter(r => r.provider === provider);
  if (!mine.length) return '';
  const cell = (k, p) => {
    const r = mine.find(x => x.combo === k && x.probe === p);
    return r ? `${MARK[r.verdict] || r.verdict}${r.flaky ? '²' : ''}` : '';
  };
  const combos = CAMPAIGN.combos.filter(c => mine.some(r => r.combo === c.id));
  const used = probes.filter(p => mine.some(r => r.probe === p));
  return [
    `### ${provider}`,
    '',
    `| K | ${used.join(' | ')} |`,
    `|---|${used.map(() => '---').join('|')}|`,
    ...combos.map(c => `| ${c.id} | ${used.map(p => cell(c.id, p)).join(' | ')} |`),
    '',
  ].join('\n');
}

/** k/N passes per (run, provider, combination, probe) over the rows of a `--repeat` run. */
function stability(rows) {
  const groups = new Map();
  for (const r of rows.filter(x => x.rep)) {
    const key = [r.run, r.provider, r.combo, r.probe].join('|');
    const g = groups.get(key) || { r, pass: 0, n: 0 };
    groups.set(key, Object.assign(g, { pass: g.pass + (r.verdict === 'PASS'), n: g.n + 1 }));
  }
  if (!groups.size) return '';
  const lines = [...groups.values()].map(
    ({ r, pass, n }) => `| ${r.run} | ${r.provider} | ${r.combo} | ${r.probe} | ${pass}/${n} |`,
  );
  return [
    '## Dispatch stability',
    '',
    '| Run | Provider | K | Probe | Passes |',
    '|---|---|---|---|---|',
  ]
    .concat(lines.sort(), '')
    .join('\n');
}

function details(rows) {
  const order = (a, b) =>
    a.provider.localeCompare(b.provider) ||
    a.combo.localeCompare(b.combo) ||
    a.probe.localeCompare(b.probe, 'en', { numeric: true });
  return [
    '| Provider | K | Probe | Verdict | Evidence | Cost | Transcript |',
    '|---|---|---|---|---|---|---|',
    ...rows
      .sort(order)
      .map(
        r =>
          `| ${r.provider} | ${r.combo} | ${r.probe} | ${r.verdict}${r.flaky ? ' (2nd try)' : ''} | ${String(r.evidence).replace(/\|/g, '\\|')} | ${cost(r)} | [raw](${r.transcript}) |`,
      ),
  ].join('\n');
}

function main() {
  const { all, latest } = latestRows();
  const spend = all.reduce((s, r) => s + (r.costUsd ?? r.estUsd ?? 0), 0);
  const premium = all
    .filter(r => r.provider === 'copilot')
    .reduce((s, r) => s + (r.premium || 0), 0);
  const counts = Object.entries(
    latest.reduce((m, r) => ((m[r.verdict] = (m[r.verdict] || 0) + 1), m), {}),
  )
    .map(([v, n]) => `${MARK[v] || ''} ${v} ${n}`)
    .join(' · ');
  const md = [
    '<!-- GENERATED by docs/audits/2026-09-27/tools/live-probe-report.js — do not edit by hand. -->',
    '',
    '# Live-prompt campaign — results',
    '',
    `Runs: ${[...new Set(all.map(r => r.run))].join(', ')} · ${latest.length} probes · ${counts}`,
    '',
    `Spend: ~$${spend.toFixed(2)} Claude (all attempts) · ${premium} Copilot premium requests.`,
    '',
    'Legend: ✅ pass · ❌ fail · 🟡 partial (no rule loaded outside its globs, some expected rules not named — soft) ·',
    '🔶 finding (works as the catalog declares, but the declaration looks wrong) · ⚪ invalid · ℹ️ control run · ² passed on retry.',
    '',
    'Probes: P1 inventory · P2 skill dispatch · P3 agent dispatch (P3n: no hint) · P4 review recall · P5 rule effect',
    '(P5c: same prompt, rules removed) · P6 rule scope · P7 hook (P7n: allowed write) · P8 settings · P9 prompt · P10 MCP.',
    '',
    '## Matrix',
    '',
    matrix('claude', latest),
    matrix('copilot', latest),
    stability(all),
    '## Combinations',
    '',
    ...CAMPAIGN.combos.map(c => `- **${c.id}** — ${c.why}`),
    '',
    '## Every probe',
    '',
    details(latest),
    '',
  ].join('\n');
  fs.writeFileSync(path.join(HERE, 'live-probe-report.md'), md);
  console.log(`wrote live-probe-report.md (${latest.length} probes)`);
}

main();
