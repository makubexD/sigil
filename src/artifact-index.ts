/**
 * The catalog's artifact index: one row per installable artifact and the Markdown page that
 * renders them. Pure data in, text out — `src/emit-artifact-index.ts` (the `npm run build` step)
 * pairs it with the package paths.
 *
 * Target membership is `add`'s own decision, not the registry's `platforms`: the caller passes
 * scaffold targets and each one runs `resolveSelection` with selector `all`, so a row's Tools
 * column agrees with an install by construction.
 *
 * @module
 */
import path from 'node:path';
import type { ArtifactKind, Pack, ResolvedCatalog, ResolvedArtifact, Target } from './types';
import { artifactLabel, KIND_ORDER, packMemberIds, resolveSelection } from './select';
import { carriedKinds, installableKinds } from './targets/capabilities';
import { installSkipReason } from './targets/install-skip';

/** One row of the artifact index: everything the page shows for an artifact. */
export interface ArtifactIndexRow {
  /** Catalog id, e.g. `csharp/cs-conventions`. */
  id: string;
  kind: ArtifactKind;
  /** Human label (`artifactLabel`): the id plus the artifact's language tag when it has one. */
  title: string;
  /** The artifact's one-line description. */
  description: string;
  /** Source file relative to the repo root, with `/` separators. */
  sourcePath: string;
  /** Names of the packs that hold the artifact, in `packs.yaml` order. */
  packs: string[];
  /** Names of the scaffold targets `add` would install the artifact into, in target order. */
  targets: string[];
  /** Reason the artifact is retired, when its frontmatter has a `deprecated:` block. */
  deprecated?: string;
}

/** The generated-file notice on the first line of the page. */
const GENERATED_NOTICE =
  '<!-- Generated by npm run build (src/emit-artifact-index.ts). Do not edit. -->';

/** Back-link line, the same one `docs/reference/capabilities.md` carries. */
const BACK_LINK = '> **Back to:** [README](../../README.md) · [Documentation index](../index.md)';

/** One sentence on what the page lists. */
const PAGE_INTRO =
  'Every installable artifact in the catalog, with the packs that hold it, the tools it installs into, and the command that installs it.';

/** The install note from the plan's Decisions table, stated once above the tables. */
const INSTALL_NOTE =
  'Each command installs for the tool set up in your project; add `--target <name>` to install for another.';

/** The table header every kind section opens with. */
const TABLE_HEADER = [
  '| Artifact | Description | Packs | Tools | Install |',
  '| --- | --- | --- | --- | --- |',
];

/**
 * Each kind's H2. `kindPlural` without a target only appends `s` ("Settingss", "Mcps"), so the
 * page names kinds here; the `Record` makes a new kind a compile error until it has a heading.
 */
const KIND_HEADINGS: Record<ArtifactKind, string> = {
  skill: 'Skills',
  agent: 'Agents',
  rule: 'Rules',
  prompt: 'Prompts',
  workflow: 'Workflows',
  hook: 'Hooks',
  settings: 'Settings',
  mcp: 'MCP servers',
  template: 'Templates',
};

/** Label used for an empty list cell (no pack, no target). */
const NONE = '—';

/** A target's name plus the ids its `all` selection installs. */
interface TargetIds {
  name: string;
  ids: Set<string>;
}

/** An artifact's frontmatter `deprecated:` block, as far as the index reads it. */
interface DeprecatedBlock {
  reason?: string;
}

/** `packs.yaml` order preserved: id → the names of the packs whose members include it. */
function collectPackNames(packs: Pack[], catalog: ResolvedCatalog): Map<string, string[]> {
  const names = new Map<string, string[]>();
  for (const pack of packs) {
    for (const id of packMemberIds(pack, catalog)) {
      const list = names.get(id) ?? [];
      list.push(pack.name);
      names.set(id, list);
    }
  }
  return names;
}

/**
 * What one target would install from `all`. A base rule dropped there as `inlined` still installs
 * on its own, which is what a row's Install column documents, so it is added back.
 */
function targetIds(target: Target, catalog: ResolvedCatalog, packs: Pack[]): TargetIds {
  const result = resolveSelection({
    selectors: ['all'],
    filters: {},
    catalog,
    packs,
    supportedKinds: installableKinds(target),
    carriedKinds: carriedKinds(target),
    targetName: target.name,
    skipReason: artifact => installSkipReason(target, artifact),
  });
  const ids = new Set(result.ids);
  for (const skipped of result.skipped) {
    if (skipped.cause === 'inlined') ids.add(skipped.id);
  }
  return { name: target.name, ids };
}

/** What each target in the caller's list would install from `all`, in that order. */
function collectTargetIds(targets: Target[], catalog: ResolvedCatalog, packs: Pack[]): TargetIds[] {
  return targets.map(target => targetIds(target, catalog, packs));
}

/** Position of `kind` in `KIND_ORDER`; unknown kinds sort last. */
function kindRank(kind: string): number {
  const index = KIND_ORDER.indexOf(kind as ArtifactKind);
  return index === -1 ? KIND_ORDER.length : index;
}

/** One artifact as a row: label, description, source path, packs and installing targets. */
function toRow(
  artifact: ResolvedArtifact,
  repoRoot: string,
  packNames: Map<string, string[]>,
  targetIds: TargetIds[],
): ArtifactIndexRow {
  const row: ArtifactIndexRow = {
    id: artifact.id,
    kind: artifact.kind,
    title: artifactLabel(artifact),
    description: (artifact.frontmatter.description as string | undefined) ?? '',
    sourcePath: path.relative(repoRoot, artifact.filePath).split(path.sep).join('/'),
    packs: packNames.get(artifact.id) ?? [],
    targets: targetIds.filter(t => t.ids.has(artifact.id)).map(t => t.name),
  };
  const deprecated = (artifact.frontmatter.deprecated as DeprecatedBlock | undefined)?.reason;
  if (deprecated !== undefined) row.deprecated = deprecated;
  return row;
}

/** `KIND_ORDER` first, then id — the page's stable row order. */
function compareRows(a: ArtifactIndexRow, b: ArtifactIndexRow): number {
  const delta = kindRank(a.kind) - kindRank(b.kind);
  if (delta !== 0) return delta;
  return a.id < b.id ? -1 : a.id > b.id ? 1 : 0;
}

/**
 * Builds the index rows for every non-template artifact in `catalog`, sorted by `KIND_ORDER` and
 * then id. `targets` is the caller's scaffold-target list (the targets `add` can install into);
 * each one's `all` selection decides the Tools column.
 */
export function buildArtifactIndex(
  catalog: ResolvedCatalog,
  packs: Pack[],
  targets: Target[],
  repoRoot: string,
): ArtifactIndexRow[] {
  const packNames = collectPackNames(packs, catalog);
  const targetIds = collectTargetIds(targets, catalog, packs);
  return catalog.artifacts
    .filter(artifact => artifact.kind !== 'template')
    .map(artifact => toRow(artifact, repoRoot, packNames, targetIds))
    .sort(compareRows);
}

/** Replaces a table cell's newlines with spaces and escapes its pipes. */
function escapeCell(text: string): string {
  return text.replace(/\r?\n|\r/g, ' ').replace(/\|/g, '\\|');
}

/** The Description cell, prefixed with the reason when the artifact is deprecated. */
function descriptionCell(row: ArtifactIndexRow): string {
  const description = escapeCell(row.description);
  return row.deprecated === undefined
    ? description
    : `**Deprecated:** ${escapeCell(row.deprecated)}. ${description}`;
}

/** A list cell: its items joined with `, `, or `—` when empty. */
function orDash(items: string[]): string {
  return items.length === 0 ? NONE : items.join(', ');
}

/** The Artifact cell: the id in code, linked to the artifact's source file. */
function artifactCell(row: ArtifactIndexRow): string {
  return `[\`${row.id}\`](../../${row.sourcePath})`;
}

/** The Install cell: the `sigil add` command, or `—` when no target installs the artifact. */
function installCell(row: ArtifactIndexRow): string {
  return row.targets.length === 0 ? NONE : `\`sigil add ${row.kind}:${row.id}\``;
}

/** One full table row. */
function rowLine(row: ArtifactIndexRow): string {
  const packs = orDash(row.packs);
  const tools = orDash(row.targets);
  return `| ${artifactCell(row)} | ${descriptionCell(row)} | ${packs} | ${tools} | ${installCell(row)} |`;
}

/** The kinds present in `rows`, in `KIND_ORDER`. */
function presentKinds(rows: ArtifactIndexRow[]): ArtifactKind[] {
  return [...new Set(rows.map(row => row.kind))].sort((a, b) => kindRank(a) - kindRank(b));
}

/** GitHub's heading slug: lowercase, spaces to hyphens. */
function slug(text: string): string {
  return text.toLowerCase().replace(/\s+/g, '-');
}

/** The line naming the tools the index covers, by `displayName ?? name`. */
function toolsLine(targets: Target[]): string {
  return `Tools: ${orDash(targets.map(target => target.displayName ?? target.name))}.`;
}

/** The contents line linking each kind's H2 by its GitHub anchor. */
function contentsLine(kinds: ArtifactKind[]): string {
  const links = kinds.map(kind => {
    const label = KIND_HEADINGS[kind];
    return `[${label}](#${slug(label)})`;
  });
  return `Contents: ${links.join(' · ')}`;
}

/** One kind's H2 and table, preceded by the blank line that separates sections. */
function renderKindSection(kind: ArtifactKind, rows: ArtifactIndexRow[]): string[] {
  const body = rows.filter(row => row.kind === kind).map(rowLine);
  return ['', `## ${KIND_HEADINGS[kind]}`, '', ...TABLE_HEADER, ...body];
}

/**
 * Renders the whole page deterministically (no timestamp): notice, title, back link, intro, the
 * install note, the tools and contents lines, then one H2 and table per kind present.
 */
export function renderArtifactIndex(rows: ArtifactIndexRow[], targets: Target[]): string {
  const kinds = presentKinds(rows);
  const lines = [
    GENERATED_NOTICE,
    '',
    '# Artifact index',
    '',
    BACK_LINK,
    '',
    PAGE_INTRO,
    '',
    INSTALL_NOTE,
    '',
    toolsLine(targets),
    '',
    contentsLine(kinds),
    ...kinds.flatMap(kind => renderKindSection(kind, rows)),
  ];
  return `${lines.join('\n')}\n`;
}
