/**
 * Renders `catalog/README.md`: the catalog's anatomy for a person browsing the folders, generated
 * from the same data the checks read (`catalog/standard.yaml`, `KIND_REGISTRY` and the targets'
 * capability tables), so the page can't drift from what `sigil sync --check` enforces. Written by
 * `npm run build` (emit-catalog-readme.ts); test/catalog-readme.test.ts fails when it is stale.
 *
 * @module
 */
import { ALL_KINDS, KIND_REGISTRY } from './kinds';
import type { CatalogStandard, FamilyDef } from './catalog-standard';
import type { ArtifactKind } from './types';
import { getAllTargets } from './targets/index';
import { supportsKind } from './targets/capabilities';

/** Where one artifact of `kind` lives inside a namespace folder. */
function kindPath(kind: ArtifactKind): string {
  const d = KIND_REGISTRY[kind];
  return d.isDirectoryBacked
    ? `\`${d.sourceDir}/<name>/${d.sourceSuffix}\` (+ optional \`references/\`)`
    : `\`${d.sourceDir}/<name>${d.sourceSuffix}\``;
}

/** How a kind reaches a project, from the targets' capability tables. */
function delivery(kind: ArtifactKind): string {
  if (!getAllTargets().some(target => supportsKind(target, kind))) {
    return 'not delivered on its own (no target emits it)';
  }
  return KIND_REGISTRY[kind].isConfig ? 'merged into a JSON config' : 'whole file';
}

function kindsTable(): string[] {
  return [
    '| Kind | File | Delivered as |',
    '| --- | --- | --- |',
    ...ALL_KINDS.map(kind => `| ${kind} | ${kindPath(kind)} | ${delivery(kind)} |`),
  ];
}

/** The reference files a family's members carry, as `name (role)` plus the stack files. */
function referencesCell(family: FamilyDef): string {
  const refs = family.references;
  if (!refs) return '—';
  const files = Object.entries(refs.files).map(([name, role]) => `${name} (${role})`);
  const perMember = Object.entries(refs.members).map(
    ([id, own]) => `${id}: ${Object.keys(own).join(', ')}`,
  );
  const stacks = refs.stacks ? ['stack-<id> (one per stack)'] : [];
  return [...stacks, ...files, ...perMember].join('; ');
}

function familiesTable(standard: CatalogStandard): string[] {
  return [
    '| Family | Kind | Title | Members | Sections | References |',
    '| --- | --- | --- | --- | --- | --- |',
    ...standard.families.map(family => {
      const members = family.members.map(id => `\`${id}\``).join(', ');
      const sections = family.sections ? String(family.sections.length) : '—';
      const title = family.title ? `${family.title} (<language>)` : '—';
      const row = [family.id, family.kind, title, members, sections, referencesCell(family)];
      return `| ${row.join(' | ')} |`;
    }),
  ];
}

