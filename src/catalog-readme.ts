/** The whole page for `standard`. */
export function renderCatalogReadme(standard: CatalogStandard): string {
  const stacks = standard.stacks
    .map(s => `\`${s.id}\` (${s.displayName}${s.home ? `, home \`${s.home}\`` : ''})`)
    .join(', ');
  return [
    ...INTRO,
    ...kindsTable(),
    ...SKILL_ANATOMY,
    ...familiesTable(standard),
    '',
    '## Stacks, severities and bases',
    '',
    `- Stacks: ${stacks}.`,
    `- Report severities, highest first: ${standard.severities.join(', ')}.`,
    `- Bases (shared rules other rules extend): ${standard.bases.map(b => `\`${b}\``).join(', ')}.`,
    '',
  ].join('\n');
}
