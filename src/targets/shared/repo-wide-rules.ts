/**
 * Repo-wide rules and the aggregate instructions file they go into, shared by every target that
 * writes one (Copilot's `.github/copilot-instructions.md`, the open-standard `AGENTS.md`). A rule is
 * repo-wide when it has no language and applies to every file; folding a narrower rule into such a
 * file would silently widen it to the whole repository.
 *
 * @module
 */
import type { ResolvedArtifact } from '../../types';
import { applyLexicon, type ProviderLexicon } from '../lexicon';

const REPO_WIDE_GLOBS: ReadonlySet<string> = new Set(['**', '**/*']);

/**
 * True when `globs` is absent, empty, or every glob in it is `**` or `**` + `/*`. It never looks at
 * `language`: Cursor's rule spec scopes on globs alone, and isRepoWideRule adds the language check.
 */
export function appliesToEveryFile(globs: readonly string[] | undefined): boolean {
  return !globs || globs.every(glob => REPO_WIDE_GLOBS.has(glob));
}

/** True for a language-less rule with no `appliesTo`, or one scoped only to every file. */
export function isRepoWideRule(rule: ResolvedArtifact): boolean {
  if (rule.frontmatter.language) return false;
  return appliesToEveryFile(rule.frontmatter.appliesTo as string[] | undefined);
}

/**
 * One instructions document from repo-wide rules: `heading`, then each rule as a `##` section. No
 * KindEmitSpec renders it, so it applies the target's lexicon itself.
 */
export function renderRulesDocument(
  heading: string,
  rules: readonly ResolvedArtifact[],
  lexicon: ProviderLexicon,
): string {
  const sections = rules.map(rule => {
    const title = rule.frontmatter.title as string;
    const body = applyLexicon(rule.resolvedBody ?? rule.body, lexicon);
    return `## ${title}\n\n${body}`;
  });
  return [
    heading,
    '',
    '<!-- Generated by sigil. Edit source in catalog/shared/rules/. -->',
    '<!-- These rules apply to every file in this repository. -->',
    '',
    ...sections,
    '',
  ].join('\n');
}
