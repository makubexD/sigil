/**
 * Tests for src/authoring/import/copilot-body.ts — pure Copilot body normalisation.
 *
 * Every heading, generated comment and `**Arguments:**` string is quoted exactly as the Copilot
 * emitters write it, including the blank lines between them.
 */
import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { normalizeCopilotBody } from '../../dist-cli/authoring/import/copilot-body';

const RULE_COMMENT = '<!-- Generated by sigil — source: catalog/typescript/ts-async.rule.md -->';
const BOUNDARY_NOTE =
  'body keeps the generated ## Boundary section; wire relatedArtifacts with sigil patch';
const CODING_NOTE =
  'body keeps the generated ## Coding guidelines to apply section; wire uses.rules with sigil patch';

/** Join body lines exactly, so the blank lines between emitted sections stay visible. */
function body(...lines: string[]): string {
  return lines.join('\n');
}

describe('rule and agent H1 + generated comment', () => {
  it('rule: strips the H1 and the generated comment', () => {
    const result = normalizeCopilotBody(
      'rule',
      body('# Async (TypeScript)', '', RULE_COMMENT, '', '## Rule one'),
    );
    assert.equal(result.title, 'Async (TypeScript)');
    assert.equal(result.body, '## Rule one');
    assert.deepEqual(result.notes, []);
  });

  it('hand-written rule: strips the H1 and keeps the text', () => {
    const result = normalizeCopilotBody('rule', body('# Style', '', 'Keep this text.'));
    assert.equal(result.title, 'Style');
    assert.equal(result.body, 'Keep this text.');
  });

  it('rule: keeps a comment that is not sigil-generated', () => {
    const result = normalizeCopilotBody(
      'rule',
      body('# Style', '', '<!-- My own note -->', '', 'Keep this text.'),
    );
    assert.equal(result.title, 'Style');
    assert.equal(result.body, body('<!-- My own note -->', '', 'Keep this text.'));
  });

  it('rule: no H1 leaves the body unchanged', () => {
    const result = normalizeCopilotBody('rule', body('## Rule one', '', 'Text.'));
    assert.equal('title' in result, false);
    assert.equal(result.body, body('## Rule one', '', 'Text.'));
  });

  it('agent: strips the H1 and keeps the Boundary block', () => {
    const result = normalizeCopilotBody(
      'agent',
      body(
        '# Reviewer',
        '',
        '## Boundary',
        '',
        'See also:',
        '- **Tester** (`tester`) — for tests',
        '',
        'You are a reviewer.',
      ),
    );
    assert.equal(result.title, 'Reviewer');
    assert.equal(
      result.body,
      body(
        '## Boundary',
        '',
        'See also:',
        '- **Tester** (`tester`) — for tests',
        '',
        'You are a reviewer.',
      ),
    );
    assert.deepEqual(result.notes, [BOUNDARY_NOTE]);
  });
});

describe('skill leading sections', () => {
  it('extracts When to Use and Arguments, keeping the following H1', () => {
    const result = normalizeCopilotBody(
      'skill',
      body(
        '## When to Use',
        '',
        'Use when writing docs.',
        '',
        '**Arguments:** [x]',
        '',
        '# Document',
        '',
        'Write the docs.',
      ),
    );
    assert.equal(result.whenToUse, 'Use when writing docs.');
    assert.equal(result.argumentHint, '[x]');
    assert.equal(result.body, body('# Document', '', 'Write the docs.'));
    assert.deepEqual(result.notes, []);
  });

  it('extracts only Arguments when it comes first', () => {
    const result = normalizeCopilotBody('skill', body('**Arguments:** [x]', '', 'Do the thing.'));
    assert.equal('whenToUse' in result, false);
    assert.equal(result.argumentHint, '[x]');
    assert.equal(result.body, 'Do the thing.');
  });

  it('keeps a leading Boundary block and extracts When to Use after it', () => {
    const result = normalizeCopilotBody(
      'skill',
      body(
        '## Boundary',
        '',
        'See also:',
        '- **Tester** (`tester`) — for tests',
        '',
        '## When to Use',
        '',
        'Use for tests.',
      ),
    );
    assert.equal(result.whenToUse, 'Use for tests.');
    assert.equal(
      result.body,
      body('## Boundary', '', 'See also:', '- **Tester** (`tester`) — for tests'),
    );
    assert.deepEqual(result.notes, [BOUNDARY_NOTE]);
  });

  it('leaves a later When to Use section in place', () => {
    const result = normalizeCopilotBody(
      'skill',
      body('Intro text.', '', '## When to Use', '', 'Not leading.'),
    );
    assert.equal('whenToUse' in result, false);
    assert.equal(result.body, body('Intro text.', '', '## When to Use', '', 'Not leading.'));
  });

  it('captures a multi-paragraph When to Use', () => {
    const result = normalizeCopilotBody(
      'skill',
      body('## When to Use', '', 'First paragraph.', '', 'Second paragraph.'),
    );
    assert.equal(result.whenToUse, 'First paragraph.\n\nSecond paragraph.');
    assert.equal(result.body, '');
  });

  it('keeps an H1 body (skills get no emitted H1)', () => {
    const result = normalizeCopilotBody('skill', body('# Heading', '', 'Body text.'));
    assert.equal('title' in result, false);
    assert.equal(result.body, body('# Heading', '', 'Body text.'));
  });
});

describe('prompt placeholders', () => {
  it('turns ${input:audience} into {{audience}} with an arg', () => {
    const result = normalizeCopilotBody('prompt', '${input:audience}');
    assert.equal(result.body, '{{audience}}');
    assert.deepEqual(result.args, [{ name: 'audience' }]);
  });
});

describe('lexicon reversal', () => {
  it('reverses the Copilot arguments value in a skill body', () => {
    const result = normalizeCopilotBody('skill', 'Use the request you were given to start.');
    assert.equal(result.body, 'Use {sigil:arguments} to start.');
  });
});

describe('remaining generated sections', () => {
  it('keeps the Coding guidelines section and notes it', () => {
    const source = body(
      'Do the skill.',
      '',
      '---',
      '',
      '## Coding guidelines to apply',
      '',
      '### Rule Title',
      '',
      'Rule body.',
    );
    const result = normalizeCopilotBody('skill', source);
    assert.equal(result.body, source);
    assert.deepEqual(result.notes, [CODING_NOTE]);
  });
});

describe('fenced code blocks', () => {
  it('rule: a fenced # heading is not the title', () => {
    const source = body('```text', '# Not a title', '```', '', 'Real content.');
    const result = normalizeCopilotBody('rule', source);
    assert.equal('title' in result, false);
    assert.equal(result.body, source);
  });

  it('skill: a fenced ## When to Use is not a heading', () => {
    const source = body(
      '```markdown',
      '## When to Use',
      '',
      'Not a heading.',
      '```',
      '',
      'Body text.',
    );
    const result = normalizeCopilotBody('skill', source);
    assert.equal('whenToUse' in result, false);
    assert.equal(result.body, source);
  });

  it('skill: a heading inside a fenced block does not end the When to Use section', () => {
    const result = normalizeCopilotBody(
      'skill',
      body(
        '## When to Use',
        '',
        'Use it for tests.',
        '',
        '```markdown',
        '# Example heading',
        '```',
        '',
        '**Arguments:** [x]',
        '',
        'Body text.',
      ),
    );
    assert.equal(result.whenToUse, 'Use it for tests.\n\n```markdown\n# Example heading\n```');
    assert.equal(result.argumentHint, '[x]');
    assert.equal(result.body, 'Body text.');
  });
});

describe('CRLF line endings', () => {
  it('rule: normalises CRLF before stripping the H1 and comment', () => {
    const source = '# Async (TypeScript)\r\n\r\n' + RULE_COMMENT + '\r\n\r\n## Rule one\r\n';
    const result = normalizeCopilotBody('rule', source);
    assert.equal(result.title, 'Async (TypeScript)');
    assert.equal(result.body, '## Rule one');
  });

  it('skill: normalises CRLF in section detection', () => {
    const source = '## When to Use\r\n\r\nUse it.\r\n\r\n**Arguments:** [x]\r\n\r\nBody.\r\n';
    const result = normalizeCopilotBody('skill', source);
    assert.equal(result.whenToUse, 'Use it.');
    assert.equal(result.argumentHint, '[x]');
    assert.equal(result.body, 'Body.');
  });
});
